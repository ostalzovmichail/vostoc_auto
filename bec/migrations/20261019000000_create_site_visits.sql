-- Счётчик посещений сайта.
--
-- Храним дневные агрегаты, а не каждое событие: для админки достаточно
-- общего числа, «сегодня» и недельной динамики, а таблица не растёт на
-- каждый просмотр. День считаем по Владивостоку — как и остальные даты
-- на сайте (VLAT, UTC+10).
CREATE TABLE IF NOT EXISTS site_visits (
    day TEXT PRIMARY KEY,
    visits INTEGER NOT NULL DEFAULT 0 CHECK (visits >= 0)
);
